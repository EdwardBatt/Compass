// Renders every tool's Compass files from one config, and reports where the files on disk differ.
//
// Two kinds of output:
//   file  — wholly owned by Compass (the Claude commands, the Cursor rule, the procedures, CI).
//   block — a marked section inside a file the project owns (CLAUDE.md, AGENTS.md, the store README).
// Hand edits to either are drift: `compass lint` fails on them and `compass sync` overwrites them.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { render } from './render.mjs'
import { REPO } from './config.mjs'

const TEMPLATES = join(dirname(fileURLToPath(import.meta.url)), '..', 'templates')
const tpl = (name) => readFileSync(join(TEMPLATES, name), 'utf8').replace(/\r\n/g, '\n')

export const BEGIN = '<!-- compass:begin — generated from compass.config.json; edit that, then run `compass sync` -->'
export const BEGIN_PREFIX = '<!-- compass:begin'
export const END = '<!-- compass:end -->'
const MD_HEADER = '<!-- Generated by Compass from compass.config.json. Edit that file, then run `compass sync`; hand edits fail `compass lint`. -->'
const YML_HEADER = '# Generated by Compass from compass.config.json. Edit that file, then run `compass sync`.'

const code = (s) => '`' + s + '`'

function list(items) {
  if (items.length <= 1) return items.join('')
  return items.slice(0, -1).join(', ') + ' and ' + items.at(-1)
}

export function authority(config) {
  if (config.authority.length) return config.authority
  const p = config.paths
  const rules = p.rules.map(code)
  const out = [
    '**The source code**, for what the system *does*' +
      (p.schema ? `, and ${code(p.schema)} for what the schema is` : '') +
      '. Always. A note that contradicts them is wrong.',
  ]
  if (p.adr) out.push(`**${code(p.adr)}**, for why something is shaped as it is. Check each decision's status line: a proposed one does not bind yet.`)
  if (rules.length) out.push(`**${list(rules)}** — the rules of working here.`)
  if (p.plan) out.push(`**${code(p.plan)}** for tasks` + (p.roadmap ? `, **${code(p.roadmap)}** for phase status` : '') + '.')
  out.push('**This store** — orientation. Dated, and assumed stale until checked.')
  return out
}

export function context(config, { tool = 'store', today = isoToday() } = {}) {
  const p = config.paths
  const claude = tool === 'claude'
  const S = config.store
  return {
    ...config,
    today,
    repo: REPO,
    plan: p.plan,
    roadmap: p.roadmap,
    adr: p.adr,
    schema: p.schema,
    rulesList: p.rules.length ? list(p.rules.map(code)) : "the project's rule files",
    authorityList: authority(config).map((a, i) => `${i + 1}. ${a}`).join('\n'),
    stateInFlight: config.state.inFlight,
    stateWaiting: config.state.waiting,
    claude,
    args: claude ? '$ARGUMENTS' : 'the task you were given',
    closeArgs: claude ? '$ARGUMENTS' : '',
    startHow: claude ? '`/compass-start <what you are about to work on>` (with no argument it proposes what to work on)' : `the steps in ${code(S + '/protocol/start.md')}`,
    closeHow: claude ? '`/compass-close`' : `the steps in ${code(S + '/protocol/close.md')}`,
  }
}

export function isoToday() {
  const t = new Date()
  return `${t.getFullYear()}-${String(t.getMonth() + 1).padStart(2, '0')}-${String(t.getDate()).padStart(2, '0')}`
}

/** Everything Compass generates for this config: [{ path, kind: 'file'|'block', content, create? }]. */
export function plan(config) {
  const T = config.targets
  const S = config.store
  const tools = new Set(config.tools)
  const store = context(config, { tool: 'store' })
  const out = []

  out.push({ path: `${S}/README.md`, kind: 'block', content: render(tpl('readme-block.md'), store) })
  out.push({ path: `${S}/protocol/start.md`, kind: 'file', content: MD_HEADER + '\n\n' + render(tpl('start.md'), store) })
  out.push({ path: `${S}/protocol/close.md`, kind: 'file', content: MD_HEADER + '\n\n' + render(tpl('close.md'), store) })

  const pointer = (tool) => render(tpl('pointer.md'), context(config, { tool }))

  if (tools.has('claude')) {
    const c = context(config, { tool: 'claude' })
    out.push({
      path: `${T.claudeCommands}/compass-start.md`,
      kind: 'file',
      content:
        '---\ndescription: Load the right project context for a task — tiered, not the whole store\nargument-hint: [what you are about to work on]\n---\n\n' +
        MD_HEADER + '\n\n' + render(tpl('start.md'), c),
    })
    out.push({
      path: `${T.claudeCommands}/compass-close.md`,
      kind: 'file',
      content:
        '---\ndescription: Write what this session learned back into the Compass store\nargument-hint: [optional — focus on a particular thing]\n---\n\n' +
        MD_HEADER + '\n\n' + render(tpl('close.md'), c),
    })
    out.push({ path: T.claudeRules, kind: 'block', content: pointer('claude'), create: '# Project instructions\n' })
  }
  if (tools.has('cursor')) {
    out.push({ path: T.cursor, kind: 'file', content: render(tpl('cursor.mdc'), { ...store, header: MD_HEADER }) })
  }
  if (tools.has('gemini')) out.push({ path: T.gemini, kind: 'block', content: pointer('gemini'), create: '# Project instructions\n' })
  if (tools.has('antigravity')) out.push({ path: T.antigravity, kind: 'block', content: pointer('antigravity'), create: '# Project rules\n' })
  if (tools.has('agents')) out.push({ path: T.agents, kind: 'block', content: pointer('agents'), create: '# Agent instructions\n' })
  if (config.ci) out.push({ path: T.ci, kind: 'file', content: YML_HEADER + '\n' + render(tpl('workflow.yml'), store) })

  for (const item of out) item.content = item.content.trimEnd() + '\n'
  return out
}

const lf = (s) => s.replace(/\r\n/g, '\n')

/** The whole file as it should be, given what is on disk now. Throws on a malformed block. */
export function expected(item, existing) {
  if (item.kind === 'file') return item.content
  const body = BEGIN + '\n' + item.content.trimEnd() + '\n' + END
  if (existing == null) return (item.create ? item.create + '\n' : '') + body + '\n'
  const text = lf(existing)
  const i = text.indexOf(BEGIN_PREFIX)
  const j = text.indexOf(END)
  if (i < 0 && j < 0) return text.replace(/\s*$/, '') + '\n\n' + body + '\n'
  if (i < 0 || j < i || text.indexOf(BEGIN_PREFIX, i + 1) >= 0) {
    throw new Error(`${item.path}: the compass:begin / compass:end markers are unbalanced — fix them by hand`)
  }
  return text.slice(0, i) + body + text.slice(j + END.length)
}

/** Lists drift without writing: [{ path, problem }]. */
export function check(root, config) {
  const drift = []
  for (const item of plan(config)) {
    const file = join(root, item.path)
    const existing = existsSync(file) ? readFileSync(file, 'utf8') : null
    if (existing == null) {
      drift.push({ path: item.path, problem: 'missing' })
      continue
    }
    try {
      if (lf(existing) !== expected(item, existing)) {
        const hasBlock = item.kind === 'block' && lf(existing).includes(BEGIN_PREFIX)
        drift.push({ path: item.path, problem: item.kind === 'block' && !hasBlock ? 'has no Compass block' : 'differs from what Compass generates' })
      }
    } catch (e) {
      drift.push({ path: item.path, problem: e.message })
    }
  }
  return drift
}

/** Writes every generated file and block. Returns the paths it changed. Keeps a file's CRLF if it had one. */
export function sync(root, config) {
  const changed = []
  for (const item of plan(config)) {
    const file = join(root, item.path)
    const existing = existsSync(file) ? readFileSync(file, 'utf8') : null
    let next = expected(item, existing)
    if (existing != null && lf(existing) === next) continue
    if (existing?.includes('\r\n')) next = next.replace(/\n/g, '\r\n')
    mkdirSync(dirname(file), { recursive: true })
    writeFileSync(file, next)
    changed.push(item.path)
  }
  return changed
}
